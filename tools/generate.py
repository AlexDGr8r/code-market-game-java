"""Generate the Java stub sources from api/code-market-api.json.

Usage: python tools/generate.py

Writes the generated types into src/main/java/javax/codemarket/. GameScript.java and
package-info.java in that folder are hand-written and left alone.
"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
API = ROOT / "api" / "code-market-api.json"
OUT = ROOT / "src" / "main" / "java" / "javax" / "codemarket"
PACKAGE = "javax.codemarket"

# Which way each direction moves on the store grid, as the game maps them (GameScripting.DirectionName).
DIRECTION_DOCS = {
    "UP": "Toward higher y: one tile is {@code (x, y + 1)}.",
    "DOWN": "Toward lower y: one tile is {@code (x, y - 1)}.",
    "LEFT": "Toward lower x: one tile is {@code (x - 1, y)}.",
    "RIGHT": "Toward higher x: one tile is {@code (x + 1, y)}.",
}

TYPE_DOCS = {
    "Robot": "The robot running this program: {@link GameScript#robot} in your script.",
    "Store": "The store the robot works in: {@link GameScript#store} in your script.",
    "Shelf": "A rack (table, shelf, fridge) that holds one product. Get one with {@link Robot#getShelf()}.",
    "Cell": "A tile of the store grid. Compare cells with {@code equals}, not {@code ==}.",
    "Customer": "A customer waiting at a register. Get one with {@link Robot#getCustomer()} or {@link Store#getWaitingCustomer()}.",
    "Order": "A customer's order, taken with {@link Robot#takeOrder()}.",
}

HEADER = (
    "// GENERATED by tools/generate.py from api/code-market-api.json ({version}). Do not edit by hand:\n"
    "// re-run the generator instead.\n"
)

CODE_REF = re.compile(
    r"(?<![\w.])("
    r"(?:robot|store|order|customer|shelf|product|cell)\.[a-zA-Z]+\([^()]*\)"  # robot.isAtTruck(), store.getStock(x, y)
    r"|(?:Product|Entity|Season|Direction)\.[A-Z_]+"  # Product.TOMATO
    r"|[a-z][a-zA-Z]+\(\)"  # removeRemaining()
    r")"
)


def javadoc_text(text: str) -> str:
    """Escape game reference text for Javadoc and mark up code references."""
    text = text.replace("`", "")
    out, last = [], 0
    for m in CODE_REF.finditer(text):
        out.append(html.escape(text[last:m.start()], quote=False))
        out.append("{@code " + m.group(1) + "}")
        last = m.end()
    out.append(html.escape(text[last:], quote=False))
    return "".join(out).replace("*/", "*&#47;").replace("@", "&#64;").replace("{&#64;code", "{@code")


def javadoc(lines, indent="    "):
    body = []
    for line in lines:
        if line == "":
            body.append(indent + " *")
        else:
            body.append(indent + " * " + line)
    return indent + "/**\n" + "\n".join(body) + "\n" + indent + " */\n"


def sentence(text: str) -> str:
    text = text.strip()
    if not text:
        return text
    text = text[0].upper() + text[1:]
    return text if text.endswith((".", "!", "?", ")")) else text + "."


def write(name: str, content: str) -> None:
    path = OUT / (name + ".java")
    path.write_text(content, encoding="utf-8", newline="\n")
    print("wrote", path.relative_to(ROOT))


def gen_interface(type_name: str, spec: dict, header: str) -> None:
    uses_list = any("List<" in m["returns"] or any("List<" in p["type"] for p in m["params"]) for m in spec["methods"])
    s = [header, f"package {PACKAGE};\n\n"]
    if uses_list:
        s.append("import java.util.List;\n\n")
    s.append(javadoc([TYPE_DOCS[type_name]], indent=""))
    s.append(f"public interface {type_name} {{\n")
    for m in spec["methods"]:
        lines = [javadoc_text(sentence(m["doc"]))]
        if m["kind"] == "Action":
            lines += ["", "<p><b>Action:</b> this changes the game" +
                      (", and the program waits while the robot carries it out." if type_name == "Robot" else ".")]
        params = ", ".join(f'{p["type"]} {p["name"]}' for p in m["params"])
        s.append("\n" + javadoc(lines))
        if m["name"] == "equals":
            s.append("    @Override\n")
        s.append(f'    {m["returns"]} {m["name"]}({params});\n')
    s.append("}\n")
    write(type_name, "".join(s))


# The types GameScript hands out; each gets a package-private dummy implementation.
STUBBED = ("Robot", "Store")


def gen_stub(type_name: str, spec: dict, header: str) -> None:
    """A package-private implementation whose every method says it only works in the game."""
    variable = spec["variable"]
    uses_list = any("List<" in m["returns"] or any("List<" in p["type"] for p in m["params"]) for m in spec["methods"])
    s = [header, f"package {PACKAGE};\n\n"]
    if uses_list:
        s.append("import java.util.List;\n\n")
    s.append(f"/** Stands in for the game's {variable} outside the game: every call throws. */\n")
    s.append(f"final class Stub{type_name} implements {type_name} {{\n")
    for m in spec["methods"]:
        params = ", ".join(f'{p["type"]} {p["name"]}' for p in m["params"])
        s.append(f'\n    @Override\n    public {m["returns"]} {m["name"]}({params}) {{\n'
                 f'        throw GameScript.notInGame("{variable}.{m["name"]}()");\n    }}\n')
    s.append(f'\n    @Override\n    public String toString() {{\n        return "{variable} (stub)";\n    }}\n')
    s.append("}\n")
    write("Stub" + type_name, "".join(s))


def gen_simple_enum(name: str, constants, doc: str, constant_docs: dict, header: str) -> None:
    s = [header, f"package {PACKAGE};\n\n", javadoc([doc], indent=""), f"public enum {name} {{\n"]
    for i, c in enumerate(constants):
        if c in constant_docs:
            s.append(javadoc([constant_docs[c]]))
        s.append(f"    {c}{',' if i < len(constants) - 1 else ';'}\n")
        if i < len(constants) - 1 and c in constant_docs:
            s.append("\n")
    s.append("}\n")
    write(name, "".join(s))


def product_summary(p: dict) -> str:
    facts = [f'${p["price"]}', "on {@link Entity#" + p["rack"] + "}"]
    for key, label in (("isAlcohol", "alcohol"), ("isAdultsOnly", "adults only (18+)"), ("isPremium", "premium"),
                       ("isElite", "elite"), ("isVending", "vending machine"), ("isInfinite", "never runs out")):
        if p[key]:
            facts.append(label)
    facts.append("in season: " + ("{@link Season#" + p["season"] + "}" if p["season"] else "all year"))
    return html.escape(p["name"], quote=False) + ": " + ", ".join(facts) + "."


def gen_product(api: dict, header: str) -> None:
    products = api["products"]
    methods = {m["name"]: m for m in api["productMethods"]}
    expected = {"isAlcohol", "isAdultsOnly", "isPremium", "isElite", "isVending", "isInfinite",
                "getPrice", "getName", "getRack", "getSeason", "isInSeason"}
    if set(methods) != expected:
        sys.exit(f"Product methods changed in the game: {sorted(set(methods) ^ expected)}; update gen_product().")
    constants = api["enums"]["Product"]
    if [p["constant"] for p in products] != constants:
        sys.exit("Product catalog and Product enum disagree; update the extractor.")

    s = [header, f"package {PACKAGE};\n\n"]
    s.append(javadoc([
        "A product the store sells.",
        "",
        "<p>The prices, racks, seasons and flags here are the game's base values, so this enum works",
        "outside the game too. {@link #isInSeason()} needs the live store and only works in game.",
    ], indent=""))
    s.append("public enum Product {\n")
    for i, p in enumerate(products):
        season = "Season." + p["season"] if p["season"] else "null"
        flags = ", ".join("true" if p[k] else "false"
                          for k in ("isAlcohol", "isAdultsOnly", "isPremium", "isElite", "isVending", "isInfinite"))
        s.append(javadoc([product_summary(p)]))
        name = json.dumps(p["name"], ensure_ascii=False)
        end = "," if i < len(products) - 1 else ";"
        s.append(f'    {p["constant"]}({name}, {p["price"]}, Entity.{p["rack"]}, {season}, {flags}){end}\n')
        if i < len(products) - 1:
            s.append("\n")

    s.append("""
    private final String displayName;
    private final int price;
    private final Entity rack;
    private final Season season;
    private final boolean alcohol, adultsOnly, premium, elite, vending, infinite;

    Product(String displayName, int price, Entity rack, Season season,
            boolean alcohol, boolean adultsOnly, boolean premium, boolean elite, boolean vending, boolean infinite) {
        this.displayName = displayName;
        this.price = price;
        this.rack = rack;
        this.season = season;
        this.alcohol = alcohol;
        this.adultsOnly = adultsOnly;
        this.premium = premium;
        this.elite = elite;
        this.vending = vending;
        this.infinite = infinite;
    }
""")
    bodies = {
        "isAlcohol": "return alcohol;", "isAdultsOnly": "return adultsOnly;", "isPremium": "return premium;",
        "isElite": "return elite;", "isVending": "return vending;", "isInfinite": "return infinite;",
        "getPrice": "return price;", "getRack": "return rack;", "getSeason": "return season;",
        "getName": "return displayName;",
        "isInSeason": "throw new UnsupportedOperationException(\n"
                      "                \"Product.isInSeason() needs the live store, so it only works inside Code Market\");",
    }
    for m in api["productMethods"]:
        lines = [javadoc_text(sentence(m["doc"]))]
        if m["name"] == "getName":
            lines += ["", "<p>Outside the game this returns the English name."]
        s.append("\n" + javadoc(lines))
        s.append(f'    public {m["returns"]} {m["name"]}() {{\n        {bodies[m["name"]]}\n    }}\n')
    s.append("}\n")
    write("Product", "".join(s))


def main() -> None:
    api = json.loads(API.read_text(encoding="utf-8"))
    header = HEADER.format(version=api.get("gameVersion", "unknown game build"))
    OUT.mkdir(parents=True, exist_ok=True)

    known = {"Robot", "Store", "Shelf", "Cell", "Customer", "Order"}
    if set(api["types"]) != known:
        sys.exit(f"Script types changed in the game: {sorted(set(api['types']) ^ known)}; update TYPE_DOCS.")
    for type_name, spec in api["types"].items():
        gen_interface(type_name, spec, header)
    for type_name in STUBBED:
        gen_stub(type_name, api["types"][type_name], header)

    enums = api["enums"]
    gen_simple_enum("Direction", enums["Direction"], "A direction on the store grid.", DIRECTION_DOCS, header)

    seasons_goods = {}
    for p in api["products"]:
        if p["season"]:
            seasons_goods.setdefault(p["season"], []).append("{@link Product#" + p["constant"] + "}")
    season_docs = {s: "Seasonal goods: " + ", ".join(g) + "." for s, g in seasons_goods.items()}
    gen_simple_enum("Season", enums["Season"],
                    "A season of the game year. Each lasts 10 in-game days; see {@link Store#getSeason()}.",
                    season_docs, header)

    holds = {}
    for p in api["products"]:
        holds.setdefault(p["rack"], []).append("{@link Product#" + p["constant"] + "}")
    entity_docs = {}
    for c in enums["Entity"]:
        parts = []
        if c in api["entityNotes"]:
            parts.append(javadoc_text(sentence(api["entityNotes"][c])))
        if c in holds:
            parts.append("Holds " + ", ".join(holds[c]) + ".")
        if parts:
            entity_docs[c] = " ".join(parts)
    entity_docs.setdefault("BAG", "The bag tile of a register, where {@link Robot#putInBag(Product)} packs goods.")
    gen_simple_enum("Entity", enums["Entity"],
                    "Something that can stand on a store tile. See {@link Store#getEntity(int, int)} and {@link Robot#look(Direction)}.",
                    entity_docs, header)

    gen_product(api, header)


if __name__ == "__main__":
    main()
